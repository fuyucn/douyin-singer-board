// Emits a TS module that carries a plugin folder as strings, so the app can
// install it without network or assets: the folder stays the source of truth.
//   node scripts/embed-plugin.mjs plugins/kugou-web src/plugin/kugouPlugin.ts KUGOU_WEB
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const [folder, out, name] = process.argv.slice(2);
if (!folder || !out || !name) {
  console.error("usage: embed-plugin.mjs <folder> <out.ts> <CONST_NAME>");
  process.exit(2);
}

const manifest = JSON.parse(readFileSync(join(folder, "plugin.json"), "utf8"));
const files = {};
for (const entry of readdirSync(folder)) {
  if (entry === "plugin.json" || entry.startsWith(".")) continue;
  // App-side TypeScript (the platform registration) lives next to the
  // runtime files but is not part of the installed web-view package.
  if (entry.endsWith(".ts")) continue;
  files[entry] = readFileSync(join(folder, entry), "utf8");
}
// The module the app reads must be in `files`.
if (!files[manifest.entry]) {
  console.error(`plugin.json entry ${manifest.entry} is not in ${folder}`);
  process.exit(1);
}

const body = [
  `// Generated by scripts/embed-plugin.mjs from ${folder}; do not edit.`,
  `import type { PluginManifest } from "./types";`,
  `export const ${name}_MANIFEST: PluginManifest = ${JSON.stringify(manifest, null, 2)};`,
  `export const ${name}_FILES: Record<string, string> = {`,
  ...Object.entries(files).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`),
  `};`,
  "",
].join("\n");
writeFileSync(out, body);
console.log(`wrote ${out}: ${Object.keys(files).join(", ")}`);
